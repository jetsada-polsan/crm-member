-- Read-only SELECT query mapped from Bplus ERP SQL01206004 (AR012004.rpt) with safe LEFT JOIN / OUTER APPLY
SELECT TOP (?)
  CAST(ARCAT.ARCAT_CODE AS varchar(32)) AS customer_category_code,
  CAST(ARCAT.ARCAT_NAME AS nvarchar(120)) AS customer_category_name,
  CAST(ARFILE.AR_CODE AS varchar(64)) AS erp_customer_code,
  CAST(ARFILE.AR_NAME AS nvarchar(255)) AS customer_name,
  CAST(CONTACT.CT_INTL AS nvarchar(40)) AS contact_title,
  CAST(NULLIF(LTRIM(RTRIM(
    COALESCE(CONTACT.CT_NAME, N'') + N' ' + COALESCE(CONTACT.CT_SURNME, N'')
  )), N'') AS nvarchar(255)) AS contact_name,
  CAST(CONTACT.CT_JOBTITLE AS nvarchar(120)) AS contact_jobtitle,
  CAST(ARCONTACT.ARC_DEFAULT AS varchar(8)) AS is_default_contact,
  CAST(CONTACT.CT_MOBILE AS varchar(64)) AS contact_mobile,
  CAST(CONTACT.CT_EMAIL AS varchar(180)) AS contact_email,
  CAST(CONTACTSTATUS.STA_NAME AS nvarchar(120)) AS contact_status,
  CAST(CONTACT.CT_REMARK AS nvarchar(500)) AS contact_remark
FROM ARFILE
INNER JOIN ARCONTACT
  ON ARFILE.AR_KEY = ARCONTACT.ARC_AR
INNER JOIN CONTACT
  ON ARCONTACT.ARC_CT = CONTACT.CT_KEY
LEFT JOIN ARCAT
  ON ARCAT.ARCAT_KEY = ARFILE.AR_ARCAT
OUTER APPLY (
  SELECT TOP 1 AB.ADDB_STA
  FROM ARADDRESS AA
  INNER JOIN ADDRBOOK AB ON AB.ADDB_KEY = AA.ARA_ADDB
  WHERE AA.ARA_AR = ARFILE.AR_KEY
  ORDER BY CASE WHEN AA.ARA_DEFAULT = 'Y' THEN 0 ELSE 1 END, AA.ARA_ADDB DESC
) AS ADDR
LEFT JOIN CONTACTSTATUS
  ON ADDR.ADDB_STA = CONTACTSTATUS.STA_KEY
WHERE ARFILE.AR_KEY >= 0
ORDER BY ARCAT.ARCAT_CODE ASC, ARFILE.AR_CODE ASC, ARCONTACT.ARC_DEFAULT DESC;
