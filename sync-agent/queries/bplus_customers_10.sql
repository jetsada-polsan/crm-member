-- Read-only SELECT query mapped from Bplus ERP ARFILE + ADDRBOOK + ARCONTACT/CONTACT + ARLINE + ARSUMMARY + ARCONDITION + SALESMAN (SQL05060001, SQL01206004)
SELECT TOP 10
  CAST(ARFILE.AR_CODE AS varchar(64)) AS erp_customer_code,
  CAST(ARFILE.AR_NAME AS nvarchar(255)) AS customer_name,
  CAST(COALESCE(NULLIF(LTRIM(RTRIM(ADDRBOOK.ADDB_PHONE)), ''), NULLIF(LTRIM(RTRIM(CONTACT_INFO.CT_MOBILE)), '')) AS varchar(64)) AS phone,
  CAST(NULLIF(LTRIM(RTRIM(
    COALESCE(CONTACT_INFO.CT_NAME, N'') + N' ' + COALESCE(CONTACT_INFO.CT_SURNME, N'')
  )), N'') AS nvarchar(255)) AS contact_name,
  CAST(CONTACT_INFO.CT_JOBTITLE AS nvarchar(120)) AS contact_jobtitle,
  CAST(CONTACT_INFO.CT_MOBILE AS varchar(64)) AS contact_mobile,
  CAST(CONTACT_INFO.CT_EMAIL AS varchar(180)) AS contact_email,
  CAST(COALESCE(SALESMAN.SLMN_CODE, ARFILE.AR_SLMNCODE) AS varchar(32)) AS salesperson_code,
  CAST(SALESMAN.SLMN_NAME AS nvarchar(120)) AS salesperson_name,
  CAST(ADDRBOOK.ADDB_PROVINCE AS nvarchar(120)) AS province,
  CAST(NULLIF(LTRIM(RTRIM(
    COALESCE(ADDRBOOK.ADDB_ADDB_1, N'') + N' ' +
    COALESCE(ADDRBOOK.ADDB_ADDB_2, N'') + N' ' +
    COALESCE(ADDRBOOK.ADDB_ADDB_3, N'') + N' ' +
    COALESCE(ADDRBOOK.ADDB_POST, N'')
  )), N'') AS nvarchar(500)) AS address,
  CAST(ARFILE.AR_ENABLE AS varchar(8)) AS ar_enable,
  CAST(ARLINE.ARL_CODE AS varchar(32)) AS route_code,
  CAST(ARLINE.ARL_NAME AS nvarchar(120)) AS route_name,
  CAST(ARSUMMARY.ARS_CRE_LIM AS decimal(16, 2)) AS credit_limit,
  CAST(ARCD.ARCD_TERM AS int) AS credit_term_days,
  CAST(ADDRBOOK.ADDB_TAX_ID AS varchar(32)) AS tax_id
FROM ARFILE
LEFT JOIN ARSUMMARY
  ON ARSUMMARY.ARS_AR = ARFILE.AR_KEY
LEFT JOIN ARLINE
  ON ARFILE.AR_ARL = ARLINE.ARL_KEY
OUTER APPLY (
  SELECT TOP 1 AC.ARCD_TERM
  FROM ARCONDITION AC
  WHERE AC.ARCD_AR = ARFILE.AR_KEY
  ORDER BY CASE WHEN AC.ARCD_DEFAULT = 'Y' THEN 0 ELSE 1 END
) AS ARCD
OUTER APPLY (
  SELECT TOP 1
    AB.ADDB_PHONE,
    AB.ADDB_PROVINCE,
    AB.ADDB_ADDB_1,
    AB.ADDB_ADDB_2,
    AB.ADDB_ADDB_3,
    AB.ADDB_POST,
    AB.ADDB_TAX_ID
  FROM ARADDRESS AA
  INNER JOIN ADDRBOOK AB ON AB.ADDB_KEY = AA.ARA_ADDB
  WHERE AA.ARA_AR = ARFILE.AR_KEY
  ORDER BY CASE WHEN AA.ARA_DEFAULT = 'Y' THEN 0 ELSE 1 END, AA.ARA_ADDB DESC
) AS ADDRBOOK
OUTER APPLY (
  SELECT TOP 1
    CT.CT_NAME,
    CT.CT_SURNME,
    CT.CT_JOBTITLE,
    CT.CT_MOBILE,
    CT.CT_EMAIL
  FROM ARCONTACT AC
  INNER JOIN CONTACT CT ON CT.CT_KEY = AC.ARC_CT
  WHERE AC.ARC_AR = ARFILE.AR_KEY
  ORDER BY CASE WHEN AC.ARC_DEFAULT = 'Y' THEN 0 ELSE 1 END, CT.CT_KEY ASC
) AS CONTACT_INFO
LEFT JOIN SALESMAN
  ON ARFILE.AR_SLMNCODE = SALESMAN.SLMN_CODE
WHERE ARFILE.AR_KEY >= 0
ORDER BY ARFILE.AR_CODE ASC;
