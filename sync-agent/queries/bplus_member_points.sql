-- Read-only SELECT query mapped from Bplus ERP MEMBER + MBPOINT + BRANCH + MBTYPE (MP0010011, MP003002)
SELECT TOP (?)
  CAST(MEMBER.MB_CODE AS varchar(64)) AS member_code,
  CAST(MEMBER.MB_INTL AS nvarchar(40)) AS title,
  CAST(NULLIF(LTRIM(RTRIM(
    COALESCE(MEMBER.MB_NAME, N'') + N' ' + COALESCE(MEMBER.MB_SURNME, N'')
  )), N'') AS nvarchar(255)) AS full_name,
  CAST(MBTYPE.MT_CODE AS varchar(32)) AS member_type_code,
  CAST(MBTYPE.MT_NAME AS nvarchar(120)) AS member_type_name,
  CAST(BRANCH.BR_CODE AS varchar(32)) AS branch_code,
  CAST(BRANCH.BR_THAIDESC AS nvarchar(120)) AS branch_name,
  CAST(MBPOINT.MBP_STATION AS varchar(32)) AS station,
  CAST(MBPOINT.MBP_REF AS varchar(80)) AS doc_ref,
  MBPOINT.MBP_DATE AS point_date,
  CAST(MBPOINT.MBP_TIME AS varchar(16)) AS point_time,
  CAST(MBPOINT.MBP_TYPE AS varchar(32)) AS point_type,
  CAST(COALESCE(MBPOINT.MBP_AMT, 0) AS decimal(16, 2)) AS amount,
  CAST(COALESCE(MBPOINT.MBP_RDM, 0) AS int) AS redeemed_points,
  CAST(COALESCE(MBPOINT.MBP_POINT, 0) AS int) AS net_points
FROM MEMBER
INNER JOIN MBPOINT
  ON MEMBER.MB_KEY = MBPOINT.MBP_MB
LEFT JOIN BRANCH
  ON MBPOINT.MBP_BRCODE = BRANCH.BR_CODE
LEFT JOIN MBTYPE
  ON MBTYPE.MT_KEY = MEMBER.MB_MT
WHERE MEMBER.MB_CODE IS NOT NULL
ORDER BY MBPOINT.MBP_DATE DESC, MBPOINT.MBP_REF DESC;
