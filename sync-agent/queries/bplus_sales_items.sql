-- Read-only SELECT query mapped from Bplus ERP TRANSTKD + SKUMASTER + ICCAT (SQL11001043, SQL11001103)
SELECT TOP (?)
  CAST(COALESCE(BRANCH.BR_CODE, '001') AS varchar(32)) AS branch_code,
  CAST(DOCTYPE.DT_DOCCODE AS varchar(32)) AS doc_type,
  CAST(DOCTYPE.DT_PROPERTIES AS int) AS dt_properties,
  CAST(DOCINFO.DI_REF AS varchar(80)) AS invoice_no,
  CAST(TRANSTKD.TRD_SEQ AS int) AS line_no,
  CAST(COALESCE(SKUMASTER.SKU_CODE, TRANSTKD.TRD_SH_CODE) AS varchar(64)) AS erp_product_code,
  CAST(COALESCE(SKUMASTER.SKU_NAME, TRANSTKD.TRD_SH_NAME) AS nvarchar(255)) AS product_name,
  CAST(ICCAT.ICCAT_CODE AS varchar(32)) AS iccat_code,
  CAST(ICCAT.ICCAT_NAME AS nvarchar(120)) AS iccat_name,
  CAST(
    CASE
      WHEN UPPER(LTRIM(RTRIM(COALESCE(ICCAT.ICCAT_CODE, '')))) IN ('CC', 'CO', 'AS', 'PK') THEN 1
      ELSE 0
    END AS bit
  ) AS is_excluded_kpi,
  CAST(TRANSTKD.TRD_QTY AS decimal(16, 4)) AS qty,
  CAST(TRANSTKD.TRD_UTQNAME AS nvarchar(30)) AS unit_name,
  CAST(TRANSTKD.TRD_U_PRC AS decimal(16, 4)) AS unit_price,
  CAST(
    CASE
      WHEN DOCTYPE.DT_PROPERTIES = 308 THEN -ABS(COALESCE(TRANSTKD.TRD_B_SELL, 0))
      ELSE COALESCE(TRANSTKD.TRD_B_SELL, 0)
    END AS decimal(16, 2)
  ) AS before_vat_amount,
  CAST(
    CASE
      WHEN DOCTYPE.DT_PROPERTIES = 308 THEN -ABS(COALESCE(TRANSTKD.TRD_B_VAT, 0))
      ELSE COALESCE(TRANSTKD.TRD_B_VAT, 0)
    END AS decimal(16, 2)
  ) AS vat_amount,
  CAST(
    CASE
      WHEN DOCTYPE.DT_PROPERTIES = 308 THEN -ABS(COALESCE(TRANSTKD.TRD_B_AMT, 0))
      ELSE COALESCE(TRANSTKD.TRD_B_AMT, 0)
    END AS decimal(16, 2)
  ) AS gross_amount,
  CAST(
    CASE
      WHEN DOCTYPE.DT_PROPERTIES = 308 THEN -ABS(COALESCE(TRANSTKD.TRD_B_SELL, 0))
      ELSE COALESCE(TRANSTKD.TRD_B_SELL, 0)
    END AS decimal(16, 2)
  ) AS net_amount,
  CAST(TRANSTKD.TRD_REFER_TRD AS varchar(64)) AS refer_trd_key,
  CAST(TRANSTKD.TRD_REFER_REF AS varchar(80)) AS refer_doc_ref
FROM DOCINFO
INNER JOIN DOCTYPE
  ON DOCINFO.DI_DT = DOCTYPE.DT_KEY
INNER JOIN TRANSTKH
  ON DOCINFO.DI_KEY = TRANSTKH.TRH_DI
INNER JOIN TRANSTKD
  ON TRANSTKH.TRH_KEY = TRANSTKD.TRD_TRH
LEFT JOIN BRANCH
  ON TRANSTKH.TRH_BR = BRANCH.BR_KEY
LEFT JOIN SKUMASTER
  ON TRANSTKD.TRD_SKU = SKUMASTER.SKU_KEY
LEFT JOIN ICCAT
  ON SKUMASTER.SKU_ICCAT = ICCAT.ICCAT_KEY
WHERE DOCTYPE.DT_PROPERTIES IN (207, 302, 307, 308, 337)
  AND DOCINFO.DI_REF IS NOT NULL
  AND DOCINFO.DI_KEY = ?
ORDER BY DOCINFO.DI_DATE DESC, DOCINFO.DI_KEY DESC, TRANSTKD.TRD_SEQ ASC;
