-- Read-only SELECT query mapped from Bplus ERP SALESMAN + SLLINE + SLTEAM + SLAREA (SQL08050001)
SELECT TOP (?)
  CAST(SALESMAN.SLMN_KEY AS bigint) AS erp_row_key,
  CAST(SALESMAN.SLMN_CODE AS varchar(32)) AS salesperson_code,
  CAST(SALESMAN.SLMN_NAME AS nvarchar(120)) AS salesperson_name,
  CAST(
    CASE
      WHEN UPPER(LTRIM(RTRIM(COALESCE(SALESMAN.SLMN_ENABLE, 'Y')))) IN ('Y', '1', 'A') THEN 1
      ELSE 0
    END AS bit
  ) AS is_active,
  CAST(SLLINE.SLL_CODE AS varchar(32)) AS line_code,
  CAST(SLLINE.SLL_NAME AS nvarchar(120)) AS line_name,
  CAST(SLTEAM.SLT_CODE AS varchar(32)) AS team_code,
  CAST(SLTEAM.SLT_NAME AS nvarchar(120)) AS team_name,
  CAST(SLAREA.SLR_CODE AS varchar(32)) AS area_code,
  CAST(SLAREA.SLR_NAME AS nvarchar(120)) AS area_name,
  CAST(SALESMAN.SLMN_REMARK AS nvarchar(500)) AS remark
FROM SALESMAN
LEFT JOIN SLLINE
  ON SALESMAN.SLMN_SLL = SLLINE.SLL_KEY
LEFT JOIN SLTEAM
  ON SALESMAN.SLMN_SLT = SLTEAM.SLT_KEY
LEFT JOIN SLAREA
  ON SALESMAN.SLMN_SLR = SLAREA.SLR_KEY
WHERE SALESMAN.SLMN_CODE IS NOT NULL
  AND SALESMAN.SLMN_KEY > ?
ORDER BY SALESMAN.SLMN_KEY ASC;
