-- Read-only SELECT query mapped from Bplus ERP SKUMASTER + UOFQTY + ICCAT (SQL11001103)
SELECT TOP (?)
  CAST(SKUMASTER.SKU_KEY AS bigint) AS erp_row_key,
  CAST(SKUMASTER.SKU_CODE AS varchar(64)) AS erp_product_code,
  CAST(SKUMASTER.SKU_NAME AS nvarchar(255)) AS product_name,
  CAST(UOFQTY.UTQ_NAME AS nvarchar(30)) AS unit,
  CAST(ICCAT.ICCAT_CODE AS varchar(32)) AS category_code,
  CAST(ICCAT.ICCAT_NAME AS nvarchar(120)) AS category_name,
  CAST(
    CASE
      WHEN UPPER(LTRIM(RTRIM(COALESCE(ICCAT.ICCAT_CODE, '')))) IN ('CC', 'CO', 'AS', 'PK') THEN 1
      ELSE 0
    END AS bit
  ) AS is_excluded_kpi
FROM SKUMASTER
LEFT JOIN UOFQTY
  ON UOFQTY.UTQ_KEY = SKUMASTER.SKU_S_UTQ
LEFT JOIN ICCAT
  ON ICCAT.ICCAT_KEY = SKUMASTER.SKU_ICCAT
WHERE SKUMASTER.SKU_KEY > ?
ORDER BY SKUMASTER.SKU_KEY ASC;
